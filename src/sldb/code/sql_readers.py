"""Readers over tree-sitter-sql nodes (PostgreSQL DDL): the `CREATE` statements, their names, columns and `--` comments.

`CREATE TABLE`, `CREATE VIEW`, `CREATE MATERIALIZED VIEW` and `CREATE INDEX` are read, at the top
level and inside `BEGIN; ... COMMIT;` (a `transaction` node), as `sqlmigrate` of Django writes them.
The name keeps its schema when written (`public.users`) and loses its double quotes: `"app_book"`
and `app_book` are the same name, also for an index (whose name the grammar gives as a `literal`).
Reading is tolerant: a statement with a local parse error still gives its object when the name
reads cleanly, and the columns whose `column_definition` has no error; only the column or the
constraint with the error is left out. tree-sitter-sql 0.3.13 does not parse
`GENERATED BY DEFAULT AS IDENTITY` (Django's primary key on Postgres) nor `CONSTRAINT name UNIQUE (...)`
inside `CREATE TABLE`, so such an `id` column gives no fact. A statement whose name does not read
gives no fact at all. Table constraints (`PRIMARY KEY (...)`, `FOREIGN KEY`, `UNIQUE` at the end) are not columns.
"""

from __future__ import annotations

from typing import Any

from sldb.code.readers import text

KINDS = {"create_table": "table", "create_view": "view", "create_materialized_view": "view", "create_index": "index"}
_NAMES = {"create_index": ("identifier", "literal")}


def creations(root: Any) -> list[tuple[Any, Any, Any]]:
    """`(statement, create node, name node)` of each `CREATE` whose name reads, in source order, also inside transactions."""
    out = []
    for stmt in root.named_children:
        if stmt.type == "transaction":
            out += creations(stmt)
        for node in (n for n in stmt.named_children if stmt.type == "statement" and n.type in KINDS):
            name = next((c for c in node.named_children if c.type in _NAMES.get(node.type, ("object_reference",))), None)
            out += [(stmt, node, name)] if name is not None and not name.has_error and name.end_byte > name.start_byte else []
    return out


def columns(node: Any) -> list[tuple[Any, Any]]:
    """`(column_definition, name node)` of a `CREATE TABLE`, in order, without the definitions that have a parse error."""
    defs = next((c for c in node.named_children if c.type == "column_definitions"), None)
    kids = defs.named_children if defs is not None else []
    return [(c, c.child_by_field_name("name")) for c in kids if c.type == "column_definition" and not c.has_error and c.child_by_field_name("name") is not None]


def sql_name(node: Any, src: bytes) -> str:
    """The name as written, without double quotes: `"public"."users"` is `public.users`."""
    return text(node, src).replace('"', "")


def sql_doc(stmt: Any, src: bytes) -> str | None:
    """The `--` lines right above `stmt`, contiguous and each on its own line, joined by newlines without `--`."""
    lines, cur, row = [], stmt.prev_sibling, stmt.start_point[0]
    while cur is not None and cur.type == "comment" and text(cur, src).startswith("--") and cur.end_point[0] + 1 == row and _own_line(cur):
        lines.insert(0, text(cur, src)[2:].strip())
        row, cur = cur.start_point[0], cur.prev_sibling
    return "\n".join(lines).strip() or None


def _own_line(comment: Any) -> bool:
    prev = comment.prev_sibling
    return prev is None or prev.end_point[0] < comment.start_point[0]


def sql_norm(node: Any, src: bytes) -> str:
    """The node's text with whitespace collapsed (no requoting: in SQL `"x"` is an identifier)."""
    return " ".join(text(node, src).split())
