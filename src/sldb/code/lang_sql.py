"""SQL (`.sql`, PostgreSQL DDL and migrations) into facts of the same form as Python's and TS's:
the module, then each table, view, index and key in source order, a table's columns and keys right
after it. tree-sitter-sql gives the objects, their names, spans and anchors (`sql_readers`); with
the extra `[postgres]`, pglast (Postgres' own parser, `sql_pg`) reads each statement again and gives
the keys and the columns' attributes (`sql_pg_keys`); facts are built in `sql_fact`.

Qualified names: an object's name as written without double quotes (`public.users`), a column's
`<table>.<column>`, a key's `<table>.<constraint>` (unnamed: `pk`, `fk`, `unique`, `~2`, `~3` per type
within the table); a repeated object takes `~2`, `~3` from `Ids`; statements inside `BEGIN; ...
COMMIT;` count. Each file is read on its own: no state across migrations. With the extra, a `CREATE
TABLE` Postgres parses gives every column (one tree-sitter-sql 0.3.13 does not parse, like Django's
`id ... GENERATED BY DEFAULT AS IDENTITY`, from pglast's span, with `parse_partial`) with `type` and the
marks `primary_key`, `unique`, `identity`, `references`, and a `constraint` fact per table key and per
`ALTER TABLE ... ADD` key (`constraint_type`, `columns`, `references {table, columns}`); `""` in a name
reads as `"`. When Postgres rejects the statement, the table keeps tree-sitter's reading and
`attrs.keys_partial`. Without the extra the reading is tree-sitter's alone, as before: no keys, no
column attributes, a column the grammar does not parse left out, and `attrs.keys_partial` on a table
whose statement has a parse error. Limits, no fact: `CHECK`, `EXCLUDE`, the other `ALTER TABLE`
actions, a statement tree-sitter does not see as a `CREATE` (its keys are lost with it); other
dialects. `ADD CONSTRAINT u UNIQUE USING INDEX idx` gives `columns: []` (the index's columns are not
read). A file not in UTF-8 keeps its byte spans (`sql_pg`, `surrogateescape`). The module's `has_error` (an anchor's `unparseable`) is set only when the file has errors
and no `CREATE` reads; `attrs.parse_errors` keeps the raw `has_error`. `imports` is always empty.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

from sldb.code.facts import fact, rels
from sldb.code.ids import Ids
from sldb.code.imports import py_module_name
from sldb.code.runtime import parse
from sldb.code.sql_fact import link_references, span_fact, sql_fact
from sldb.code.sql_fingerprints import sql_fingerprints
from sldb.code.sql_names import exact_name
from sldb.code.sql_pg import pg_statements
from sldb.code.sql_pg_keys import alter_parts, create_parts
from sldb.code.sql_readers import KINDS, columns, creations, sql_doc, sql_name


def scan_sql_file(rel: str, root: Path, idgen: Ids) -> list[dict[str, Any]]:
    src = (root / rel).read_bytes()
    rootn, module, pg = parse(src, rel).root_node, py_module_name(rel), pg_statements(src)
    ctx = {"rel": rel, "module": module, "src": src, "digest": "sha256:" + hashlib.sha256(src).hexdigest(), "mid": idgen.take(module or "__init__"),
           "ids": idgen, "local": Ids(), "tables": {}, "pg": pg, "name": sql_name if pg is None else exact_name}
    found = creations(rootn)
    steps = [(n.start_byte, _object_facts, (s, n, name)) for s, n, name in found] + [(p["start"], _alter_facts, (p,)) for p in pg or []]
    facts = [_module_fact(rootn, ctx, rootn.has_error and not found)]
    for _, step, args in sorted(steps, key=lambda s: s[0]):
        facts += step(*args, ctx)
    return link_references(facts)


def _module_fact(rootn: Any, ctx: dict[str, Any], unreadable: bool) -> dict[str, Any]:
    """`has_error` (an anchor's `unparseable`) only when nothing reads; `parse_errors` says whether the tree has any error."""
    module, nlines = ctx["module"], len(ctx["src"].decode("utf-8", "replace").splitlines())
    return fact(id=ctx["mid"], kind="module", name=module.rsplit(".", 1)[-1] if module else "__init__", qualified_name=module, path=ctx["rel"],
                span={"start_line": 1, "end_line": max(nlines, 1)}, source_hash=ctx["digest"], doc=None, relations=rels(None, []),
                attrs={"native_kind": rootn.type, "module": module, "imports": [], "nested_imports": [], "has_error": unreadable, "parse_errors": rootn.has_error},
                fingerprints=sql_fingerprints(rootn, None, None, ctx["src"]))


def _object_facts(stmt: Any, node: Any, name: Any, ctx: dict[str, Any]) -> list[dict[str, Any]]:
    """The table, view or index, then (for a table) its columns and its keys, contained in it."""
    src = ctx["src"]
    obj = sql_fact(node, name, KINDS[node.type], ctx["local"].take(ctx["name"](name, src)), sql_doc(stmt, src), ctx["mid"], ctx)
    if obj["kind"] != "table":
        return [obj]
    ctx["tables"].setdefault(obj["qualified_name"], obj)
    pg = next((p for p in ctx["pg"] or [] if p["start"] <= node.start_byte < p["end"]), None)
    parts = create_parts(pg) if pg is not None else None
    if parts is None:
        return _tree_sitter_table(stmt, node, obj, ctx)
    return [obj] + [_column_fact(c, node, obj, ctx) for c in parts[0]] + [_key_fact(k, obj["qualified_name"], obj["id"], ctx) for k in parts[1]]


def _tree_sitter_table(stmt: Any, node: Any, obj: dict[str, Any], ctx: dict[str, Any]) -> list[dict[str, Any]]:
    """Without pglast's reading: the columns tree-sitter parses whole, and `keys_partial` when keys may be missing."""
    obj["attrs"].update({"keys_partial": True} if ctx["pg"] is not None or stmt.has_error else {})
    return [obj] + [sql_fact(col, cname, "column", f"{obj['qualified_name']}.{ctx['name'](cname, ctx['src'])}", None, obj["id"], ctx) for col, cname in columns(node)]


def _column_fact(col: dict[str, Any], node: Any, obj: dict[str, Any], ctx: dict[str, Any]) -> dict[str, Any]:
    """From tree-sitter's `column_definition` when it starts where Postgres' column does and parses; else from pglast's span."""
    clean = next(((c, n) for c, n in columns(node) if c.start_byte == col["span"]["start"]), None)
    qualified = f"{obj['qualified_name']}.{col['name']}"
    out = sql_fact(*clean, "column", qualified, None, obj["id"], ctx) if clean else span_fact("column", col["name"], qualified, obj["id"], col["span"], "ColumnDef", ctx)
    out["attrs"].update(col["attrs"] if clean else {**col["attrs"], "parse_partial": True})
    return out


def _key_fact(key: dict[str, Any], table: str, owner: str, ctx: dict[str, Any]) -> dict[str, Any]:
    name = key["name"] or key["short"]
    out = span_fact("constraint", name, ctx["local"].take(f"{table}.{name}"), owner, key["span"], "Constraint", ctx)
    out["attrs"].update({k: key[k] for k in ("constraint_type", "columns", "references") if k in key})
    return out


def _alter_facts(pg: dict[str, Any], ctx: dict[str, Any]) -> list[dict[str, Any]]:
    """The keys of an `ALTER TABLE ... ADD`, under the table read before it, or the module; Postgres rejecting it marks that table."""
    parts = alter_parts(pg)
    if parts is None:
        return []
    table, keys = parts[0], parts[1]
    if keys is None:
        ctx["tables"].get(table, {"attrs": {}})["attrs"]["keys_partial"] = True
        return []
    return [_key_fact(k, table, ctx["tables"][table]["id"] if table in ctx["tables"] else ctx["mid"], ctx) for k in keys]
