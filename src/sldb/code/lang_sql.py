"""SQL (`.sql`, PostgreSQL DDL and migrations) into facts of the same form as Python's and TS's:
the module, then each table, view and index in source order, a table's columns right after it
(readers in `sql_readers`). Each file is read on its own: no `ALTER TABLE`, no state across migrations.

The module's qualified name is its path without extension, like `py_module_name`. An object's
qualified name is its name as written without double quotes (`public.users` or `users`), a column's
is `<table>.<column>`; statements inside `BEGIN; ... COMMIT;` count, and a statement with a local
parse error keeps its object and clean columns. Limit: a column the grammar does not parse is left
out, typically Django's `id ... GENERATED BY DEFAULT AS IDENTITY` (tree-sitter-sql 0.3.13);
an object repeated in the same file takes `~2`, `~3` from `Ids`, and its columns hang from the
suffixed name. The anchor symbol is that qualified name. `imports` is always empty. Since local
errors are tolerated, the module's `has_error` (which makes an anchor `unparseable`) is set only
when the file has errors and no `CREATE` reads; `attrs.parse_errors` keeps the raw `has_error`.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

from sldb.code.facts import fact, rels
from sldb.code.ids import Ids
from sldb.code.imports import py_module_name
from sldb.code.runtime import parse
from sldb.code.sql_fingerprints import sql_fingerprints
from sldb.code.sql_readers import KINDS, columns, creations, sql_doc, sql_name, sql_norm


def scan_sql_file(rel: str, root: Path, idgen: Ids) -> list[dict[str, Any]]:
    src = (root / rel).read_bytes()
    rootn, module = parse(src, rel).root_node, py_module_name(rel)
    ctx = {"rel": rel, "module": module, "src": src, "digest": "sha256:" + hashlib.sha256(src).hexdigest(), "mid": idgen.take(module or "__init__"), "ids": idgen}
    found, local = creations(rootn), Ids()
    facts = [_module_fact(rootn, ctx, rootn.has_error and not found)]
    for stmt, node, name in found:
        facts += _object_facts(stmt, node, name, local.take(sql_name(name, src)), ctx)
    return facts


def _module_fact(rootn: Any, ctx: dict[str, Any], unreadable: bool) -> dict[str, Any]:
    """`has_error` (an anchor's `unparseable`) only when nothing reads; `parse_errors` says whether the tree has any error."""
    module, nlines = ctx["module"], len(ctx["src"].decode("utf-8", "replace").splitlines())
    return fact(id=ctx["mid"], kind="module", name=module.rsplit(".", 1)[-1] if module else "__init__", qualified_name=module, path=ctx["rel"],
                span={"start_line": 1, "end_line": max(nlines, 1)}, source_hash=ctx["digest"], doc=None, relations=rels(None, []),
                attrs={"native_kind": rootn.type, "module": module, "imports": [], "nested_imports": [], "has_error": unreadable, "parse_errors": rootn.has_error},
                fingerprints=sql_fingerprints(rootn, None, None, ctx["src"]))


def _object_facts(stmt: Any, node: Any, name: Any, qualified: str, ctx: dict[str, Any]) -> list[dict[str, Any]]:
    """The table, view or index, then (for a table) its columns, contained in it."""
    obj = _fact(node, name, KINDS[node.type], qualified, sql_doc(stmt, ctx["src"]), ctx["mid"], ctx)
    cols = [(col, cname, f"{qualified}.{sql_name(cname, ctx['src'])}") for col, cname in columns(node)]
    return [obj] + [_fact(col, cname, "column", q, None, obj["id"], ctx) for col, cname, q in cols]


def _fact(node: Any, name: Any, kind: str, qualified: str, doc: str | None, owner: str, ctx: dict[str, Any]) -> dict[str, Any]:
    module, src = ctx["module"], ctx["src"]
    return fact(id=ctx["ids"].take(f"{module}.{qualified}" if module else qualified), kind=kind, name=sql_name(name, src).rsplit(".", 1)[-1], qualified_name=qualified,
                path=ctx["rel"], span={"start_line": node.start_point[0] + 1, "end_line": node.end_point[0] + 1}, source_hash=ctx["digest"],
                signature=sql_norm(node, src), doc=doc, relations=rels(owner), attrs={"native_kind": node.type, "module": module},
                fingerprints=sql_fingerprints(node, name, doc, src))
