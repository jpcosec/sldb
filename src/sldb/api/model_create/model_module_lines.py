"""The lines of a generated model module: header, class attributes and field declarations."""

from __future__ import annotations

from sldb.api.model_create.field_decl import FieldDecl

HEADER = '"""Generated by `sldb.api.create_model` from the declaration of {name};\nregenerated from it, never edited by hand."""\n'


def module_lines(name: str, module: str, cls: str, template: str, fields: tuple[FieldDecl, ...], attrs: dict) -> list[str]:
    """Header, class attributes (`attrs`: dunder name -> value) and one block per field."""
    lines = _header_lines(name, module, cls, template)
    lines += [f"    {key} = {value!r}\n" for key, value in attrs.items() if value is not None]
    return lines + [f.source() for f in fields]


def _header_lines(name: str, module: str, cls: str, template: str) -> list[str]:
    """Docstring, imports, class statement, class docstring and `__template__`."""
    return [
        HEADER.format(name=name),
        "from typing import Literal  # noqa: F401\n",
        "from pydantic import Field\n",
        f"from {module} import {cls}\n\n",
        f"class {name}({cls}):",
        f'    """{name}, declared by an agent through `sldb.api.create_model`."""\n',
        f"    __template__ = {quoted(template)}\n",
    ]


def field_section(f: FieldDecl) -> str:
    """The default template section of one field."""
    slot = f"- ⸢rev,list•{f.name}⸥" if f.type == "list[str]" else f"⸢rev•{f.name}⸥"
    return f"## {f.name.replace('_', ' ').capitalize()}\n\n{slot}"


def composition_section(comp_name: str) -> str:
    """The default template section of one composition."""
    return f"## {comp_name.replace('_', ' ').capitalize()}\n\n⸢render•{comp_name}⸥"


def quoted(text: str) -> str:
    """Triple quotes when the text allows them, as the hand-written models; repr otherwise."""
    if '"""' in text or "\\" in text or text.endswith('"'):
        return repr(text)
    return f'"""{text}"""'
